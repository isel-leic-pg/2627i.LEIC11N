fun main() {
    // Exemplo de \t e \n
    println("Nome:\tLucas\nIdade:\t25")
    // Saída:
    // Nome:    Lucas
    // Idade:   25

    // Exemplo de \b
    println("Texto\b") 
    // Saída: Text (o 'o' foi apagado pelo backspace)

    // Exemplo de \r
    println("Janela\rPorta")
    // Saída: Portaa (o caret que estava no final da palavra 'Porta' voltou ao início, com o \r e escreveu por cima)
}
